const UNKNOWN = ["11111", "10001", "10001", "10001", "10001", "10001", "11111"];

export function glyphOf(ch: string): string[] {
  if (ch === " ") return ["00000", "00000", "00000", "00000", "00000", "00000", "00000"];
  return FONT[ch] ?? UNKNOWN;
}

/** Draw uppercase pixel text. Returns the width in pixels. */
export function drawText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  scale: number,
  color: string,
): number {
  ctx.fillStyle = color;
  const lines = text.toUpperCase().split("\n");
  let max = 0;
  lines.forEach((line, li) => {
    let cx = x;
    const cy = y + li * 8 * scale;
    for (const ch of line) {
      const glyph = glyphOf(ch);
      for (let r = 0; r < 7; r++) {
        const row = glyph[r] ?? "";
        for (let c = 0; c < 5; c++) {
          if (row[c] === "1") ctx.fillRect(cx + c * scale, cy + r * scale, scale, scale);
        }
      }
      cx += 6 * scale;
    }
    max = Math.max(max, cx - x);
  });
  return max;
}

export function measureText(text: string, scale: number): { width: number; height: number } {
  const lines = text.toUpperCase().split("\n");
  const width = lines.reduce((m, line) => Math.max(m, line.length * 6 * scale), 0);
  const height = lines.length * 7 * scale + (lines.length - 1) * scale;
  return { width, height };
}
